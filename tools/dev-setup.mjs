#!/usr/bin/env node
/**
 * Local development setup. Creates a random DEV-ONLY admin password, writes its
 * PBKDF2 hash to .dev.vars (read by `wrangler dev`) and the password itself to
 * .dev.password (both gitignored). Nothing is printed. Re-run to rotate.
 * This is never your production password; set that with tools/hash-password.mjs.
 */
import { writeFileSync, existsSync } from 'node:fs';
import { webcrypto as crypto } from 'node:crypto';

const ITER = 100_000;
const b64url = (b) => Buffer.from(b).toString('base64url');

if (existsSync('.dev.password') && !process.argv.includes('--rotate')) {
  console.log('Dev credentials already exist (.dev.password). Use --rotate to replace them.');
  process.exit(0);
}
const password = b64url(crypto.getRandomValues(new Uint8Array(18)));
const salt = crypto.getRandomValues(new Uint8Array(16));
const key = await crypto.subtle.importKey('raw', new TextEncoder().encode(password), 'PBKDF2', false, [
  'deriveBits',
]);
const bits = await crypto.subtle.deriveBits(
  { name: 'PBKDF2', hash: 'SHA-256', salt, iterations: ITER },
  key,
  256,
);
const hash = `pbkdf2-sha256$${ITER}$${b64url(salt)}$${b64url(new Uint8Array(bits))}`;
writeFileSync(
  '.dev.vars',
  `# Local only (gitignored). Generated by tools/dev-setup.mjs\nADMIN_PASSWORD_HASH='${hash}'\n`,
);
writeFileSync('.dev.password', `${password}\n`);
console.log('Wrote .dev.vars (hash) and .dev.password (your local dev password). Both are gitignored.');
